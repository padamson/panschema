//! Postgres DDL writer
//!
//! Writes the LinkML IR to Postgres `CREATE TABLE` DDL: concrete classes,
//! scalar attributes, enums, and single-valued class references. See
//! `docs/features/24-postgres-ddl-writer.md` for the full design,
//! including constructs not yet covered here.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use crate::io::{IoError, IoResult, Writer};
use crate::linkml::{ClassDefinition, SchemaDefinition, SlotDefinition};

/// Writer for Postgres DDL (`CREATE TABLE` / `CREATE TYPE`).
pub struct PostgresWriter;

impl PostgresWriter {
    pub fn new() -> Self {
        Self
    }

    /// Render the schema to a complete DDL script.
    pub fn render(&self, schema: &SchemaDefinition) -> String {
        render(schema)
    }
}

/// The DDL body without the `@generated by panschema v<version>` banner.
///
/// A migration runner checksums a migration's raw SQL text with no
/// normalization and refuses to run when a stored checksum no longer
/// matches. Stamping the tool version into the file would change that
/// checksum on every panschema upgrade and abort the run, so `migrate`
/// emits this instead of [`PostgresWriter::render`]. Everything here is
/// derived from the schema alone.
pub fn render_migration_body(schema: &SchemaDefinition) -> String {
    render_body(schema)
}

impl Default for PostgresWriter {
    fn default() -> Self {
        Self::new()
    }
}

impl Writer for PostgresWriter {
    fn write(&self, schema: &SchemaDefinition, output: &Path) -> IoResult<()> {
        crate::io::ensure_output_parent(output)?;
        std::fs::write(output, self.render(schema)).map_err(IoError::Io)?;
        Ok(())
    }

    fn format_id(&self) -> &str {
        "postgres"
    }

    /// This writer's three gap classes, as prose over the same data the
    /// typed diagnostics ([`skipped_classes`], [`skipped_rules`],
    /// [`skipped_constraints`]) expose: a class with no table, a rule with
    /// no `CHECK` form, and a per-element constraint with no form over an
    /// array column. The cross-format default contributes nothing here —
    /// this format projects `rules` and `unique_keys`.
    fn projection_gaps(&self, schema: &SchemaDefinition) -> Vec<String> {
        let mut gaps = crate::diagnostics::classes_with_unprojected_constructs(schema, "postgres")
            .into_iter()
            .map(|u| u.message("postgres"))
            .collect::<Vec<_>>();
        gaps.extend(
            skipped_classes(schema)
                .into_iter()
                .map(|s| format!("class `{}` has no postgres table: {}", s.class, s.reason)),
        );
        gaps.extend(skipped_rules(schema).into_iter().map(|s| {
            format!(
                "rule `{}` on class `{}` is not emitted as a postgres CHECK: {}",
                s.rule, s.class, s.reason
            )
        }));
        gaps.extend(skipped_constraints(schema).into_iter().map(|s| {
            format!(
                "constraint on slot `{}` of class `{}` is not emitted: {}",
                s.slot, s.class, s.reason
            )
        }));
        gaps.extend(crate::diagnostics::slot_specialization_gaps(
            schema, "postgres",
        ));
        gaps
    }
}

/// Double-quote a Postgres identifier, doubling any embedded `"`. Applied
/// to every identifier this writer interpolates into SQL — table, column,
/// enum type, and constraint names. Quoting is unconditional: it makes
/// reserved words (a class named `Order`) legal, and it confines a
/// hostile or merely unusual name to the identifier position instead of
/// letting it alter the statement. Names are snake_cased (lowercased)
/// first, so quoting doesn't change how well-formed names resolve.
fn quote_ident(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

fn render(schema: &SchemaDefinition) -> String {
    let mut out = String::new();
    writeln!(
        out,
        "-- @generated by panschema v{}",
        env!("CARGO_PKG_VERSION")
    )
    .ok();
    out.push_str(&render_body(schema));
    out
}

fn render_body(schema: &SchemaDefinition) -> String {
    let mut out = String::new();
    writeln!(out, "-- Schema: {}", schema.name).ok();
    writeln!(out).ok();

    for enum_name in referenced_enums(schema) {
        let def = &schema.enums[enum_name];
        let type_name = crate::casing::snake_case(enum_name);
        let values: Vec<String> = def
            .permissible_values
            .keys()
            .map(|v| format!("'{}'", v.replace('\'', "''")))
            .collect();
        writeln!(
            out,
            "CREATE TYPE {} AS ENUM ({});",
            quote_ident(&type_name),
            values.join(", ")
        )
        .ok();
    }
    writeln!(out).ok();

    // Foreign-key constraints are deferred: added via `ALTER TABLE` after
    // every `CREATE TABLE`, so declaration order (and cycles between
    // classes) never matter — the script still applies in one pass.
    let mut fk_constraints = Vec::new();
    let mut linking_tables: Vec<LinkingTable> = Vec::new();
    let holders = roots_holding(schema);
    let skips = compute_skips_with(schema, &holders);

    for (class_name, class) in &schema.classes {
        if class.r#abstract {
            // Not meant to be instantiated — nothing to hold a row.
            continue;
        }
        if skips.contains_key(class_name) {
            // Not projected (is_a, any_of, a key-named class with no single
            // scope or a clashing name, or a dependency on a class with no
            // table) — see `skipped_classes` for the diagnostic surfaced to
            // the caller.
            continue;
        }
        let table = crate::casing::snake_case(class_name);
        let effective = crate::linkml_resolve::resolve_effective_slots(class, schema);
        let key = class_primary_key(class, schema);
        let pk_slot = key.slot.clone();

        writeln!(out, "CREATE TABLE {} (", quote_ident(&table)).ok();
        let mut lines = vec![format!(
            "    {} {} PRIMARY KEY{}",
            quote_ident(&key.col),
            key.sql_type,
            if pk_slot.is_none() {
                " DEFAULT gen_random_uuid()"
            } else {
                ""
            }
        )];
        let scope = record_scope(class_name, class, schema, &holders);
        if let Some(RecordScope::Scoped {
            col,
            sql_type,
            root_table,
            root_col,
            nullable,
            ..
        }) = &scope
        {
            lines.push(format!(
                "    {} {sql_type}{}",
                quote_ident(col),
                if *nullable { "" } else { " NOT NULL" }
            ));
            fk_constraints.push(FkConstraint {
                from_table: table.clone(),
                from_col: col.clone(),
                to_table: root_table.clone(),
                to_col: root_col.clone(),
                constraint_name: format!("{table}_{col}_fkey"),
            });
        }
        // Slot name → the column name it actually resolves to, so the
        // table-level constraints below (`unique_keys`, `rules`) can name
        // the real columns. The single source of column naming, shared with
        // `skipped_rules` so its skip decision can't drift from what `render`
        // actually emits.
        let slot_columns = slot_column_map(class, schema);
        for (slot_name, slot) in &effective {
            if pk_slot.as_deref() == Some(slot_name.as_str()) {
                continue;
            }
            // A multivalued class range has no column here; it becomes its
            // own table, emitted once every class table exists.
            if let Some(link) = linking_table_for(class_name, class, slot_name, slot, schema) {
                linking_tables.push(link);
                continue;
            }
            let col = &slot_columns[slot_name];
            // NOT NULL follows the *effective* lower bound: an explicit
            // `minimum_cardinality >= 1` makes a column required even without
            // the `required` flag, the same reconciliation HTML and SHACL use.
            let not_null = if crate::linkml_resolve::effective_cardinality(slot).required {
                " NOT NULL"
            } else {
                ""
            };
            let range = slot.range.as_deref();
            if let Some(target_class) = range.and_then(|r| schema.classes.get_key_value(r)) {
                let (target_name, target_def) = target_class;
                let target_key = class_primary_key(target_def, schema);
                lines.push(format!(
                    "    {} {}{not_null}",
                    quote_ident(col),
                    target_key.sql_type
                ));
                fk_constraints.push(FkConstraint {
                    from_table: table.clone(),
                    from_col: col.clone(),
                    to_table: crate::casing::snake_case(target_name),
                    to_col: target_key.col,
                    constraint_name: format!(
                        "{table}_{}_fkey",
                        crate::casing::snake_case(slot_name)
                    ),
                });
            } else {
                // A multivalued scalar becomes an array of its element type.
                // Its value constraints are per-element and have no CHECK
                // form over an array, so they are dropped here and reported
                // by `skipped_constraints`.
                let sql_type = match is_multivalued(slot) {
                    true => format!("{}[]", sql_type_for_slot_range(range, schema)),
                    false => sql_type_for_slot_range(range, schema),
                };
                let checks = match is_multivalued(slot) {
                    true => String::new(),
                    false => column_checks(col, slot),
                };
                lines.push(format!(
                    "    {} {sql_type}{not_null}{checks}",
                    quote_ident(col)
                ));
            }
        }
        // A key is unique within its scope: the root that holds the record,
        // or every row when no root names one. NULLS NOT DISTINCT keeps the
        // rows without a scope unique among themselves too.
        match &scope {
            Some(RecordScope::Scoped { key_col, col, .. }) => lines.push(format!(
                "    CONSTRAINT {} UNIQUE NULLS NOT DISTINCT ({}, {})",
                quote_ident(&format!("{table}_record_key")),
                quote_ident(col),
                quote_ident(key_col)
            )),
            Some(RecordScope::Unscoped { key_col }) => lines.push(format!(
                "    CONSTRAINT {} UNIQUE ({})",
                quote_ident(&format!("{table}_record_key")),
                quote_ident(key_col)
            )),
            Some(RecordScope::Ambiguous(_)) | None => {}
        }
        // Table-level UNIQUE constraints from `unique_keys`. A key that
        // names a slot the class doesn't have is dropped entirely rather
        // than emitting a UNIQUE over a nonexistent column — the same
        // gap `diagnostics::unresolved_unique_key_slots` warns about on
        // the CLI path, enforced here so the writer never emits broken
        // DDL even if that warning is ignored.
        for (key_name, key) in &class.unique_keys {
            let cols: Option<Vec<&String>> = key
                .unique_key_slots
                .iter()
                .map(|s| slot_columns.get(s.as_str()))
                .collect();
            if let Some(cols) = cols {
                let col_list = cols
                    .iter()
                    .map(|c| quote_ident(c))
                    .collect::<Vec<_>>()
                    .join(", ");
                lines.push(format!(
                    "    CONSTRAINT {} UNIQUE ({col_list})",
                    quote_ident(&format!(
                        "{table}_{}_key",
                        crate::casing::snake_case(key_name)
                    ))
                ));
            }
        }
        // Conditional `CHECK` constraints from `rules`: `NOT (pre) OR (post)`,
        // the standard SQL encoding of "when precondition holds, postcondition
        // must too". A rule that can't be expressed as a column CHECK is
        // dropped here (and separately surfaced by `skipped_rules` on the CLI
        // path) rather than emitted broken.
        let array_slots = array_column_slots(class, schema);
        for (i, rule) in class.rules.iter().enumerate() {
            if let (Some(pre), Some(post)) = (&rule.preconditions, &rule.postconditions)
                && let (Some(p_sql), Some(q_sql)) = (
                    rule_conditions_to_sql(pre, &slot_columns, &array_slots),
                    rule_conditions_to_sql(post, &slot_columns, &array_slots),
                )
            {
                lines.push(format!(
                    "    CONSTRAINT {} CHECK (NOT ({p_sql}) OR ({q_sql}))",
                    quote_ident(&format!("{table}_rule{i}_check"))
                ));
            }
        }
        writeln!(out, "{}", lines.join(",\n")).ok();
        writeln!(out, ");").ok();
        writeln!(out).ok();
    }

    // Linking tables come after every class table, so a reader sees the
    // entities first and the relationships between them second. Their
    // foreign keys join the deferred set like any other.
    for link in &linking_tables {
        writeln!(out, "CREATE TABLE {} (", quote_ident(&link.name)).ok();
        writeln!(
            out,
            "    {} {} NOT NULL,",
            quote_ident(&link.owner_col),
            link.owner_type
        )
        .ok();
        writeln!(
            out,
            "    {} {} NOT NULL,",
            quote_ident(&link.target_col),
            link.target_type
        )
        .ok();
        writeln!(
            out,
            "    PRIMARY KEY ({}, {})",
            quote_ident(&link.owner_col),
            quote_ident(&link.target_col)
        )
        .ok();
        writeln!(out, ");").ok();
        writeln!(out).ok();

        for (from_col, to_table, to_col, side) in [
            (
                &link.owner_col,
                &link.owner_table,
                &link.owner_pk,
                &link.owner_col,
            ),
            (
                &link.target_col,
                &link.target_table,
                &link.target_pk,
                &link.target_col,
            ),
        ] {
            fk_constraints.push(FkConstraint {
                from_table: link.name.clone(),
                from_col: from_col.clone(),
                to_table: to_table.clone(),
                to_col: to_col.clone(),
                constraint_name: format!("{}_{side}_fkey", link.name),
            });
        }
    }

    for fk in &fk_constraints {
        writeln!(
            out,
            "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({});",
            quote_ident(&fk.from_table),
            quote_ident(&fk.constraint_name),
            quote_ident(&fk.from_col),
            quote_ident(&fk.to_table),
            quote_ident(&fk.to_col)
        )
        .ok();
    }

    out
}

/// Inline `CHECK` clauses for a scalar column, from the slot's value
/// constraints — the leading-space-prefixed suffix appended to the column
/// definition. Empty when the slot has none.
///
/// - `pattern` → `CHECK (col ~ 'regex')` (single quotes doubled so the
///   literal can't break the statement, same escaping the enum values use).
/// - `minimum_value` / `maximum_value` → a single `CHECK` combining both
///   with `AND` when both are set, or just the one side when only one is.
fn column_checks(col: &str, slot: &crate::linkml::SlotDefinition) -> String {
    let col = quote_ident(col);
    let mut checks = String::new();
    if let Some(p) = &slot.pattern {
        checks.push_str(&format!(" CHECK ({col} ~ '{}')", p.replace('\'', "''")));
    }
    let bound = match (slot.minimum_value, slot.maximum_value) {
        (Some(min), Some(max)) => Some(format!("{col} >= {min} AND {col} <= {max}")),
        (Some(min), None) => Some(format!("{col} >= {min}")),
        (None, Some(max)) => Some(format!("{col} <= {max}")),
        (None, None) => None,
    };
    if let Some(b) = bound {
        checks.push_str(&format!(" CHECK ({b})"));
    }
    checks
}

/// Whether the slot's range names a class in this schema, as opposed to a
/// scalar or an enum. The distinction decides both the column form (foreign
/// key or linking table, versus a plain or array column) and whether a
/// multivalued slot is in scope at all.
fn is_class_range(slot: &SlotDefinition, schema: &SchemaDefinition) -> bool {
    slot.range
        .as_deref()
        .is_some_and(|r| schema.classes.contains_key(r))
}

/// Whether this slot holds a list: the flag, or a `maximum_cardinality`
/// above one, as every other writer reads it.
fn is_multivalued(slot: &SlotDefinition) -> bool {
    crate::linkml_resolve::effective_cardinality(slot).multivalued
}

/// Every effective slot of `class` mapped to the column name it becomes:
/// an identifier to the primary-key column, a single-valued class-range
/// slot to its `{slot}_{target_pk}` foreign-key column, and any other
/// scalar slot, a key included, to its bare `snake_case` name. The one place column
/// naming is decided, so `render` (emission) and `skipped_rules`
/// (diagnostic) can't disagree about which columns exist.
fn slot_column_map(class: &ClassDefinition, schema: &SchemaDefinition) -> BTreeMap<String, String> {
    let effective = crate::linkml_resolve::resolve_effective_slots(class, schema);
    let key = class_primary_key(class, schema);
    let pk_slot = key.slot;

    let mut map = BTreeMap::new();
    if let Some(pk) = &pk_slot {
        map.insert(pk.clone(), key.col.clone());
    }
    for (slot_name, slot) in &effective {
        if pk_slot.as_deref() == Some(slot_name.as_str()) {
            continue;
        }
        // A multivalued class range lives in its own linking table, so it
        // has no column on this table at all. Leaving it out is what keeps
        // `unique_keys` and `rules` from naming a column that isn't there.
        if is_multivalued(slot) && is_class_range(slot, schema) {
            continue;
        }
        let col = match slot.range.as_deref().and_then(|r| schema.classes.get(r)) {
            Some(target_def) => format!(
                "{}_{}",
                crate::casing::snake_case(slot_name),
                class_primary_key(target_def, schema).col
            ),
            None => crate::casing::snake_case(slot_name),
        };
        map.insert(slot_name.clone(), col);
    }
    map
}

/// A many-to-many table standing for one multivalued class-range slot.
///
/// Both sides are `NOT NULL` and together form the primary key, so a
/// target cannot be listed twice under the same slot. See feature 24 slice
/// 5 for why every such slot gets one, rather than a foreign key on the
/// child when the relationship looks like ownership.
struct LinkingTable {
    name: String,
    owner_col: String,
    owner_type: String,
    owner_table: String,
    owner_pk: String,
    target_col: String,
    target_type: String,
    target_table: String,
    target_pk: String,
}

/// The linking table for `slot_name` on `class`, or `None` when the slot
/// isn't a multivalued class range.
fn linking_table_for(
    class_name: &str,
    class: &ClassDefinition,
    slot_name: &str,
    slot: &SlotDefinition,
    schema: &SchemaDefinition,
) -> Option<LinkingTable> {
    if !is_multivalued(slot) {
        return None;
    }
    let target_def = slot.range.as_deref().and_then(|r| schema.classes.get(r))?;
    let owner_table = crate::casing::snake_case(class_name);
    let target_table = crate::casing::snake_case(slot.range.as_deref()?);
    let owner_key = class_primary_key(class, schema);
    let target_key = class_primary_key(target_def, schema);
    let slot_col = crate::casing::snake_case(slot_name);
    Some(LinkingTable {
        // Named for the slot rather than the target class, so two slots
        // onto one class stay two distinct relationships.
        name: format!("{owner_table}_{slot_col}"),
        owner_col: format!("{owner_table}_{}", owner_key.col),
        owner_type: owner_key.sql_type,
        owner_table,
        owner_pk: owner_key.col,
        target_col: format!("{slot_col}_{}", target_key.col),
        target_type: target_key.sql_type,
        target_table,
        target_pk: target_key.col,
    })
}

/// Map a rule's `slot_conditions` to a SQL boolean expression — the `AND`
/// of every condition's predicates — or `None` if the conditions can't be
/// expressed as a column `CHECK`. Unexpressible when: the map is empty; a
/// referenced slot isn't a column of this class (`slot_columns` miss); a
/// condition carries a `range` or cardinality field (no single-column SQL
/// form); a condition puts a pattern or value bound on an array column
/// (no per-element `CHECK` form exists — the same gap `pattern`/bounds
/// facets have there); or a condition has no expressible field at all.
///
/// On an array column an equals condition is membership — `'v' = ANY(col)`
/// — the same at-least-one reading the native validator and the SHACL
/// projection give it, so all three projections enforce one semantics.
/// The field → predicate mapping mirrors the HTML "when … then …"
/// sentence (`rules.rs`'s `describe_slot_condition`).
fn rule_conditions_to_sql(
    conds: &crate::linkml::RuleConditions,
    slot_columns: &BTreeMap<String, String>,
    array_slots: &std::collections::BTreeSet<String>,
) -> Option<String> {
    if conds.slot_conditions.is_empty() {
        return None;
    }
    let mut preds = Vec::new();
    for (slot, cond) in &conds.slot_conditions {
        let col = quote_ident(slot_columns.get(slot.as_str())?);
        let is_array = array_slots.contains(slot.as_str());
        // Fields with no single-column CHECK form make the whole rule
        // unexpressible (the HTML card can still render them).
        if cond.range.is_some()
            || cond.minimum_cardinality.is_some()
            || cond.maximum_cardinality.is_some()
        {
            return None;
        }
        if is_array
            && (cond.pattern.is_some()
                || cond.minimum_value.is_some()
                || cond.maximum_value.is_some())
        {
            return None;
        }
        if let Some(v) = &cond.equals_string {
            let literal = v.replace('\'', "''");
            preds.push(if is_array {
                format!("'{literal}' = ANY({col})")
            } else {
                format!("{col} = '{literal}'")
            });
        }
        if let Some(n) = cond.equals_number {
            preds.push(if is_array {
                format!("{n} = ANY({col})")
            } else {
                format!("{col} = {n}")
            });
        }
        if cond.required {
            preds.push(format!("{col} IS NOT NULL"));
        }
        if let Some(p) = &cond.pattern {
            preds.push(format!("{col} ~ '{}'", p.replace('\'', "''")));
        }
        if let Some(m) = cond.minimum_value {
            preds.push(format!("{col} >= {m}"));
        }
        if let Some(m) = cond.maximum_value {
            preds.push(format!("{col} <= {m}"));
        }
    }
    if preds.is_empty() {
        return None;
    }
    Some(preds.join(" AND "))
}

/// The class's slots that render as array columns — multivalued scalars
/// and enums — where equality means membership and per-element facet
/// forms don't exist.
fn array_column_slots(
    class: &ClassDefinition,
    schema: &SchemaDefinition,
) -> std::collections::BTreeSet<String> {
    crate::linkml_resolve::resolve_effective_slots(class, schema)
        .into_iter()
        .filter(|(_, slot)| is_multivalued(slot) && !is_class_range(slot, schema))
        .map(|(name, _)| name)
        .collect()
}

/// A deferred foreign-key constraint, added after every table is declared.
struct FkConstraint {
    from_table: String,
    from_col: String,
    to_table: String,
    to_col: String,
    constraint_name: String,
}

/// A class this writer doesn't project to a table, and why.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SkippedClass {
    pub class: String,
    pub reason: String,
}

/// Classes [`render`] skips, with a diagnostic naming why:
///
/// - `is_a`, or an `any_of` slot, which this writer does not yet support;
/// - a class its key names that more than one root with an identifier
///   holds, so its key has no single scope;
/// - a key-named class with a column or constraint that would take a name
///   its record key uses (`uuid`, the scope column, `<table>_record_key`,
///   the scope column's foreign key);
/// - a class whose table would reference one that is never created,
///   through a class-range slot or its scope column, however many steps
///   away.
///
/// An abstract class isn't reported here — it's not a gap, it deliberately
/// gets no table.
pub fn skipped_classes(schema: &SchemaDefinition) -> Vec<SkippedClass> {
    compute_skips(schema)
        .into_iter()
        .map(|(class, reason)| SkippedClass { class, reason })
        .collect()
}

/// A slot-level value constraint [`render`] can't project to a `CHECK`, and
/// why.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SkippedConstraint {
    pub class: String,
    pub slot: String,
    pub reason: String,
}

/// Value constraints [`render`] drops, with a diagnostic naming each.
///
/// A `pattern` or a `minimum_value`/`maximum_value` on a **multivalued**
/// slot constrains each element, and Postgres has no `CHECK` form for that
/// over an array column: `arr ~ 'p'` is not an operator, and the subquery
/// over `unnest` that would express it is not allowed inside a `CHECK`.
/// Emitting one anyway yields a script that parses and then fails when the
/// database runs it, which is the worst of the three options. So the
/// constraint is dropped and named here instead.
pub fn skipped_constraints(schema: &SchemaDefinition) -> Vec<SkippedConstraint> {
    let skips = compute_skips(schema);
    let mut out = Vec::new();
    for (class_name, class) in &schema.classes {
        if class.r#abstract || skips.contains_key(class_name) {
            continue;
        }
        let effective = crate::linkml_resolve::resolve_effective_slots(class, schema);
        for (slot_name, slot) in &effective {
            if !is_multivalued(slot) || is_class_range(slot, schema) {
                continue;
            }
            let dropped = [
                slot.pattern.is_some().then_some("pattern"),
                (slot.minimum_value.is_some() || slot.maximum_value.is_some())
                    .then_some("value bounds"),
            ]
            .into_iter()
            .flatten()
            .collect::<Vec<_>>();
            if dropped.is_empty() {
                continue;
            }
            out.push(SkippedConstraint {
                class: class_name.clone(),
                slot: slot_name.clone(),
                reason: format!(
                    "{} on a multivalued slot constrains each element, which has no Postgres \
                     CHECK form over an array column",
                    dropped.join(" and ")
                ),
            });
        }
    }
    out
}

/// A `rules` entry [`render`] can't project to a `CHECK` constraint, and why.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SkippedRule {
    pub class: String,
    /// The rule's title, or `rule #<n>` (its position) when it has none.
    pub rule: String,
    pub reason: String,
}

/// Rules [`render`] can't emit as a conditional `CHECK`, with a diagnostic
/// naming each. A rule is unexpressible when it has only one of
/// pre/postconditions, or a condition side that can't become a column
/// predicate (empty, a `range`/cardinality field, or a slot the class
/// doesn't have). Shares [`slot_column_map`] and [`rule_conditions_to_sql`]
/// with `render`, so this reports exactly the rules `render` drops — no
/// drift between the warning and the emitted DDL. Classes that get no table
/// at all (abstract, or skipped per [`compute_skips`]) contribute no rule
/// diagnostics — their omission is already covered by [`skipped_classes`].
pub fn skipped_rules(schema: &SchemaDefinition) -> Vec<SkippedRule> {
    let skips = compute_skips(schema);
    let mut out = Vec::new();
    for (class_name, class) in &schema.classes {
        if class.r#abstract || skips.contains_key(class_name) || class.rules.is_empty() {
            continue;
        }
        let slot_columns = slot_column_map(class, schema);
        let array_slots = array_column_slots(class, schema);
        for (i, rule) in class.rules.iter().enumerate() {
            if let Some(reason) = rule_skip_reason(rule, &slot_columns, &array_slots) {
                out.push(SkippedRule {
                    class: class_name.clone(),
                    rule: crate::rules::rule_label(rule, i),
                    reason,
                });
            }
        }
    }
    out
}

/// Why [`render`] would skip `rule`, or `None` if it emits a `CHECK`. Calls
/// the same [`rule_conditions_to_sql`] `render` uses, so the decision is
/// identical.
fn rule_skip_reason(
    rule: &crate::linkml::ClassRule,
    slot_columns: &BTreeMap<String, String>,
    array_slots: &std::collections::BTreeSet<String>,
) -> Option<String> {
    match (&rule.preconditions, &rule.postconditions) {
        (Some(pre), Some(post)) => {
            if rule_conditions_to_sql(pre, slot_columns, array_slots).is_none() {
                Some(
                    "its preconditions can't be expressed as a Postgres CHECK (empty, a `range`/cardinality condition, a pattern or value bound on an array column, or a slot the class doesn't have)"
                        .to_string(),
                )
            } else if rule_conditions_to_sql(post, slot_columns, array_slots).is_none() {
                Some(
                    "its postconditions can't be expressed as a Postgres CHECK (empty, a `range`/cardinality condition, a pattern or value bound on an array column, or a slot the class doesn't have)"
                        .to_string(),
                )
            } else {
                None
            }
        }
        _ => Some("a Postgres CHECK needs both preconditions and postconditions".to_string()),
    }
}

/// The shared computation behind [`skipped_classes`] and [`render`]'s own
/// exclusion of out-of-scope classes — one pass so the two can't drift.
fn compute_skips(schema: &SchemaDefinition) -> BTreeMap<String, String> {
    compute_skips_with(schema, &roots_holding(schema))
}

/// [`compute_skips`] over an already computed [`roots_holding`].
fn compute_skips_with(
    schema: &SchemaDefinition,
    holders: &BTreeMap<String, std::collections::BTreeSet<String>>,
) -> BTreeMap<String, String> {
    let mut skips = BTreeMap::new();
    for (name, class) in &schema.classes {
        if class.r#abstract {
            continue;
        }
        if class.is_a.is_some() {
            skips.insert(
                name.clone(),
                "uses `is_a`, which this writer does not yet support".to_string(),
            );
            continue;
        }
        let effective = crate::linkml_resolve::resolve_effective_slots(class, schema);
        if let Some((slot_name, _)) = effective.iter().find(|(_, s)| !s.any_of.is_empty()) {
            skips.insert(
                name.clone(),
                format!(
                    "has polymorphic `any_of` slot `{slot_name}`, which this writer does not yet support"
                ),
            );
            continue;
        }
        if let Some(reason) = record_scope_conflict(name, class, schema, holders) {
            skips.insert(name.clone(), reason);
        }
    }

    // A class whose table would reference one that is never created —
    // through a class-range slot's foreign key, or its scope column's —
    // is skipped too, rather than emit broken DDL. Repeated until nothing
    // changes, so a chain of dependencies is followed to its end: a root
    // is a hub, and dropping one reaches every class scoped to it and
    // every class referencing those. A pass that skips nothing new ends it,
    // so there are never more passes than classes.
    for _ in 0..schema.classes.len() {
        let cascaded: Vec<(String, String)> = schema
            .classes
            .iter()
            .filter(|(name, class)| !class.r#abstract && !skips.contains_key(*name))
            .filter_map(|(name, class)| {
                missing_table_dependency(name, class, schema, holders, &skips)
                    .map(|reason| (name.clone(), reason))
            })
            .collect();
        let before = skips.len();
        for (name, reason) in cascaded {
            skips.entry(name).or_insert(reason);
        }
        if skips.len() == before {
            break;
        }
    }

    skips
}

/// Why `class`'s table would reference a table that is never created —
/// an abstract or skipped class, through a class-range slot or the scope
/// column — or `None` when every table it references exists.
fn missing_table_dependency(
    class_name: &str,
    class: &ClassDefinition,
    schema: &SchemaDefinition,
    holders: &BTreeMap<String, std::collections::BTreeSet<String>>,
    skips: &BTreeMap<String, String>,
) -> Option<String> {
    let has_table = |name: &str| {
        schema.classes.get(name).is_some_and(|c| !c.r#abstract) && !skips.contains_key(name)
    };
    let effective = crate::linkml_resolve::resolve_effective_slots(class, schema);
    if let Some((slot_name, range)) = effective.iter().find_map(|(slot_name, slot)| {
        slot.range
            .as_deref()
            .filter(|range| schema.classes.contains_key(*range) && !has_table(range))
            .map(|range| (slot_name, range))
    }) {
        return Some(format!(
            "references class `{range}` (via slot `{slot_name}`), which is unsupported or itself skipped"
        ));
    }
    match record_scope(class_name, class, schema, holders) {
        Some(RecordScope::Scoped { root, .. }) if !has_table(&root) => Some(format!(
            "its records are scoped to root `{root}`, which is unsupported or itself skipped"
        )),
        _ => None,
    }
}

/// How a class's table is keyed: the primary-key column, its SQL type,
/// and the slot whose values fill it (`None` when the key is synthetic).
struct TableKey {
    col: String,
    sql_type: String,
    slot: Option<String>,
}

/// The primary key for a class: its identifier, when the identifier names
/// its records
/// ([`record_id_slot`](crate::linkml_resolve::record_id_slot)); a
/// synthetic `uuid` when a key does, since a key is unique only within
/// its scope and so cannot key the table; and a synthetic `id` when
/// nothing names them.
fn class_primary_key(class: &ClassDefinition, schema: &SchemaDefinition) -> TableKey {
    let effective = crate::linkml_resolve::resolve_effective_slots(class, schema);
    let synthetic = |col: &str| TableKey {
        col: col.to_string(),
        sql_type: "uuid".to_string(),
        slot: None,
    };
    match crate::linkml_resolve::record_id_slot(&effective) {
        Some((name, slot)) if slot.identifier => TableKey {
            col: crate::casing::snake_case(name),
            sql_type: sql_type_for_slot_range(slot.range.as_deref(), schema),
            slot: Some(name.clone()),
        },
        Some(_) => synthetic(KEYED_SURROGATE),
        None => synthetic("id"),
    }
}

/// The synthetic primary-key column of a class its key names. Not `id`,
/// which the key slot itself is usually called.
const KEYED_SURROGATE: &str = "uuid";

/// Where the records of a class its key names are unique.
enum RecordScope {
    /// No identifier-named root holds the class: the key is unique among
    /// all its rows.
    Unscoped { key_col: String },
    /// One identifier-named root holds the class — a root keyed on its
    /// identifier, the one a dataset's records mint beneath: the key is
    /// unique within each of that root's records, named by the scope column `col`. The
    /// column is `nullable` when a root without an identifier also holds
    /// the class, since those records have no scope.
    Scoped {
        key_col: String,
        root: String,
        col: String,
        sql_type: String,
        root_table: String,
        root_col: String,
        nullable: bool,
    },
    /// More than one identifier-named root holds the class.
    Ambiguous(Vec<String>),
}

/// The scope of `class`'s records, or `None` when no key names them. The
/// instance model mints a key-named record beneath the identifier of the
/// dataset root holding it, and unscoped under a root without one; this is
/// the same rule over the schema.
fn record_scope(
    class_name: &str,
    class: &ClassDefinition,
    schema: &SchemaDefinition,
    holders: &BTreeMap<String, std::collections::BTreeSet<String>>,
) -> Option<RecordScope> {
    let effective = crate::linkml_resolve::resolve_effective_slots(class, schema);
    let (key_name, _) =
        crate::linkml_resolve::record_id_slot(&effective).filter(|(_, slot)| !slot.identifier)?;
    // The column the key becomes, which a class-range key names after its
    // target's key (`<key>_<target_pk>`).
    let key_col = slot_column_map(class, schema)
        .remove(key_name)
        .unwrap_or_else(|| crate::casing::snake_case(key_name));
    let (scoping, shared): (Vec<&String>, Vec<&String>) = holders
        .get(class_name)
        .into_iter()
        .flatten()
        .partition(|root| {
            class_primary_key(&schema.classes[root.as_str()], schema)
                .slot
                .is_some()
        });
    Some(match scoping.as_slice() {
        [] => RecordScope::Unscoped { key_col },
        [root] => {
            let root_key = class_primary_key(&schema.classes[root.as_str()], schema);
            let root_table = crate::casing::snake_case(root);
            RecordScope::Scoped {
                key_col,
                root: (*root).clone(),
                col: format!("{root_table}_{}", root_key.col),
                sql_type: root_key.sql_type,
                root_table,
                root_col: root_key.col,
                nullable: !shared.is_empty(),
            }
        }
        _ => RecordScope::Ambiguous(scoping.into_iter().cloned().collect()),
    })
}

/// Why `class` cannot be projected because of its record scope: held by
/// more than one scoping root, a slot column that takes the name of the
/// synthetic key or the scope column, or a constraint that takes the name
/// of the record key's (`<table>_record_key`, the scope column's
/// `<table>_<scope>_fkey`).
fn record_scope_conflict(
    class_name: &str,
    class: &ClassDefinition,
    schema: &SchemaDefinition,
    holders: &BTreeMap<String, std::collections::BTreeSet<String>>,
) -> Option<String> {
    let taken = match record_scope(class_name, class, schema, holders)? {
        RecordScope::Ambiguous(roots) => {
            let roots = roots
                .iter()
                .map(|r| format!("`{r}`"))
                .collect::<Vec<_>>()
                .join(", ");
            return Some(format!(
                "its key is unique within the root holding its records, and more than one root \
                 with an identifier holds them ({roots}), so the scope is ambiguous"
            ));
        }
        RecordScope::Scoped { col, .. } => vec![KEYED_SURROGATE.to_string(), col],
        RecordScope::Unscoped { .. } => vec![KEYED_SURROGATE.to_string()],
    };
    let columns = slot_column_map(class, schema);
    let effective = crate::linkml_resolve::resolve_effective_slots(class, schema);
    if let Some((key_name, _)) = crate::linkml_resolve::record_id_slot(&effective)
        && !columns.contains_key(key_name)
    {
        return Some(format!(
            "key slot `{key_name}` is multivalued, so it has no column to be unique"
        ));
    }
    if let Some((slot, col)) = columns.into_iter().find(|(_, col)| taken.contains(col)) {
        return Some(format!(
            "slot `{slot}` becomes column `{col}`, which this writer uses for its record key"
        ));
    }

    let table = crate::casing::snake_case(class_name);
    let record_key = format!("{table}_record_key");
    // The constraint's index shares one namespace with every table.
    if relation_names(schema).contains(&record_key) {
        return Some(format!(
            "a table would be named `{record_key}`, which this writer uses for its record key"
        ));
    }
    if let Some(name) = class
        .unique_keys
        .keys()
        .find(|name| format!("{table}_{}_key", crate::casing::snake_case(name)) == record_key)
    {
        return Some(format!(
            "unique key `{name}` would be named `{record_key}`, which this writer uses for its \
             record key"
        ));
    }
    let scope_fkey = taken.get(1).map(|scope| format!("{table}_{scope}_fkey"))?;
    crate::linkml_resolve::resolve_effective_slots(class, schema)
        .into_iter()
        .find(|(slot_name, slot)| {
            !is_multivalued(slot)
                && is_class_range(slot, schema)
                && format!("{table}_{}_fkey", crate::casing::snake_case(slot_name)) == scope_fkey
        })
        .map(|(slot_name, _)| {
            format!(
                "slot `{slot_name}`'s foreign key would be named `{scope_fkey}`, which this \
                 writer uses for the scope column's"
            )
        })
}

/// Every class mapped to the `tree_root` classes that hold its records: the
/// ranges of a root's collections (its multivalued class-range slots), and
/// whatever the root or a class it holds contains through an inlined slot,
/// transitively. A reference holds nothing.
fn roots_holding(
    schema: &SchemaDefinition,
) -> BTreeMap<String, std::collections::BTreeSet<String>> {
    let mut holders: BTreeMap<String, std::collections::BTreeSet<String>> = BTreeMap::new();
    for (root_name, root) in schema.classes.iter().filter(|(_, c)| c.tree_root) {
        let mut queue: Vec<String> = crate::linkml_resolve::resolve_effective_slots(root, schema)
            .into_values()
            .filter_map(|slot| {
                let (target, target_def) = schema.classes.get_key_value(slot.range.as_deref()?)?;
                (is_multivalued(&slot) || inlines(&slot, target_def, schema))
                    .then(|| target.clone())
            })
            .collect();
        let mut seen = std::collections::BTreeSet::new();
        while let Some(held) = queue.pop() {
            if !seen.insert(held.clone()) {
                continue;
            }
            holders
                .entry(held.clone())
                .or_default()
                .insert(root_name.clone());
            let held_def = &schema.classes[&held];
            for slot in crate::linkml_resolve::resolve_effective_slots(held_def, schema).values() {
                if let Some((target, target_def)) = slot
                    .range
                    .as_deref()
                    .and_then(|r| schema.classes.get_key_value(r))
                    && inlines(slot, target_def, schema)
                {
                    queue.push(target.clone());
                }
            }
        }
    }
    holders
}

/// Every table name the script could create: one per non-abstract class,
/// and one per multivalued class-range slot's linking table.
fn relation_names(schema: &SchemaDefinition) -> std::collections::BTreeSet<String> {
    let mut names = std::collections::BTreeSet::new();
    for (name, class) in schema.classes.iter().filter(|(_, c)| !c.r#abstract) {
        let table = crate::casing::snake_case(name);
        for (slot_name, slot) in crate::linkml_resolve::resolve_effective_slots(class, schema) {
            if is_multivalued(&slot) && is_class_range(&slot, schema) {
                names.insert(format!("{table}_{}", crate::casing::snake_case(&slot_name)));
            }
        }
        names.insert(table);
    }
    names
}

/// Whether a class-range slot contains its value rather than referencing
/// it: the model's one inlining rule
/// ([`is_inlined`](crate::linkml_resolve::is_inlined)), read against the
/// target's effective slots.
fn inlines(slot: &SlotDefinition, target: &ClassDefinition, schema: &SchemaDefinition) -> bool {
    let effective = crate::linkml_resolve::resolve_effective_slots(target, schema);
    crate::linkml_resolve::is_inlined(slot, effective.values())
}

/// Every enum referenced by an effective slot of any class, in name-sorted
/// (deterministic) order — the set of `CREATE TYPE`s to emit before any
/// table that references one.
fn referenced_enums(schema: &SchemaDefinition) -> Vec<&str> {
    let mut names = std::collections::BTreeSet::new();
    for class in schema.classes.values() {
        let effective = crate::linkml_resolve::resolve_effective_slots(class, schema);
        for slot in effective.values() {
            if let Some(range) = &slot.range
                && let Some((enum_name, _)) = schema.enums.get_key_value(range)
            {
                names.insert(enum_name.as_str());
            }
        }
    }
    names.into_iter().collect()
}

/// The Postgres column type for a slot's range: an enum type name (quoted —
/// it's an identifier this writer itself declares) if the range resolves to
/// a declared enum, else the scalar type mapping (a builtin type keyword,
/// never quoted).
fn sql_type_for_slot_range(range: Option<&str>, schema: &SchemaDefinition) -> String {
    let range = range.unwrap_or("string");
    if schema.enums.contains_key(range) {
        quote_ident(&crate::casing::snake_case(range))
    } else {
        sql_type_for_range(range, schema).to_string()
    }
}

/// Map a LinkML scalar range to its Postgres column type. Mirrors
/// `rust_writer::type_for_range`'s alias set for the primitive ranges.
///
/// `string`/`str`/`uri`/`uriorcurie`/`curie`/`ncname`/`objectidentifier`/
/// `nodeidentifier` all resolve to `"text"` — the same value the `_`
/// fallback below produces for any other unrecognized name — so they're
/// covered by the fallback rather than listed as their own match arm.
fn sql_type_for_range(range: &str, schema: &SchemaDefinition) -> &'static str {
    // Resolve through the shared primitive table — aliases, a custom
    // `types:` entry's `typeof` chain, a root type's `uri:` — so this
    // column agrees with the primitive every other projection resolves the
    // same range to; non-primitives fall through to `text`.
    let canonical = match crate::primitives::effective_primitive(schema, range) {
        Some(p) => p,
        None => range,
    };
    match canonical {
        "integer" => "integer",
        "boolean" => "boolean",
        "float" | "double" | "decimal" => "double precision",
        "date" => "date",
        "datetime" => "timestamptz",
        "time" => "time",
        _ => "text",
    }
}

